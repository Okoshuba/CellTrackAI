package com.kubaice.celltrackai.domain.ai

import javax.inject.Inject
import javax.inject.Singleton

@Singleton
class MockScientificAssistantService @Inject constructor() : ScientificAssistantService {

    override suspend fun answerQuestion(
        cultureId: String,
        question: String
    ): AssistantResponse {
        val q = question.lowercase()

        val (answer, refIds) = when {
            q.contains("split") || q.contains("passage") || q.contains("subculture") -> Pair(
                "For standard adherent cell cultures, subculture when cells reach 80-90% confluency. " +
                        "1) Aspirate media and wash gently with DPBS (w/o Ca2+/Mg2+).\n" +
                        "2) Add 0.25% Trypsin-EDTA and incubate at 37°C for 3-5 minutes until 90%+ detachment.\n" +
                        "3) Neutralize with complete media containing 10% FBS, centrifuge at 200xg for 5 min, and re-seed at 1.5 - 2.0 x 10^4 cells/cm².",
                listOf("SOP-CELL-PAS-01", "REC-SPLIT-80")
            )
            q.contains("doubling") || q.contains("growth rate") || q.contains("kinetics") -> Pair(
                "Typical population doubling times:\n" +
                        "• HeLa: ~20-24 hours\n" +
                        "• iPSCs: ~18-22 hours (requires mTeSR1 / Geltrex)\n" +
                        "• Vero E6: ~24-30 hours\n" +
                        "• HEK293: ~24-28 hours\n" +
                        "If doubling time exceeds 36 hours, inspect for latent contamination, mycoplasma, or depleted FBS batch.",
                listOf("LIT-GROWTH-KINETICS-2024")
            )
            q.contains("contamination") || q.contains("yellow") || q.contains("turbid") -> Pair(
                "Sudden media yellowing (pH drop) indicates rapid bacterial or yeast proliferation. " +
                        "Immediately quarantine the culture flask. Do not open under shared laminar flow hoods. " +
                        "Perform Mycoplasma PCR testing and verify autoclave cycle parameters for glassware.",
                listOf("SOP-CONTAM-ISOLATION-03")
            )
            q.contains("media") || q.contains("feed") || q.contains("change") -> Pair(
                "Recommended media replenishment schedule is every 48 hours for standard high-density cultures. " +
                "Pre-warm DMEM / RPMI 1640 to 37°C in a water bath before addition. Avoid direct streaming onto the cell monolayer.",
                listOf("SOP-MEDIA-PREP-02")
            )
            else -> Pair(
                "Based on logged culture parameters for culture #$cultureId, cell viability and morphology remain within optimal operational thresholds. " +
                        "Maintain standard 37°C, 5% CO2 humidified incubation conditions.",
                listOf("REC-GENERAL-OBS-01")
            )
        }

        val limitation = "Generated by CellTrack AI Assistant based on cell biology literature and active culture log parameters. Always verify protocol adjustments against lab safety manuals."

        return AssistantResponse(
            answerText = answer,
            referencedRecordIds = refIds,
            confidenceAndLimitationsNote = limitation
        )
    }
}
